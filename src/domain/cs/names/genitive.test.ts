/** [1st case, expected 2nd case]. „?“ as expected: unsure → kept as typed and flagged. */
type Case = readonly [string, string];

function table(sex: Sex, role: 'given' | 'family', cases: readonly Case[]) {
  it.each(cases)(`%s → %s`, (input, expected) => {
    const result = declineToken(input, sex, role);
    if (expected === '?') {
      expect(result.confidence).toBe('low');
      expect(result.form).toBe(input);
    } else {
      expect(result.form).toBe(expected);
      expect(result.confidence).not.toBe('low');
    }
  });
}

